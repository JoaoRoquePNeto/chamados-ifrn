CREATE TABLE setores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    sigla VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    setor_id BIGINT NOT NULL REFERENCES setores(id)
);

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    matricula VARCHAR(30) NOT NULL,
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('SOLICITANTE', 'TECNICO')),
    setor_id BIGINT REFERENCES setores(id),
    CHECK ((tipo = 'TECNICO' AND setor_id IS NOT NULL) OR (tipo = 'SOLICITANTE' AND setor_id IS NULL))
);

CREATE TABLE chamados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(150) NOT NULL,
    descricao VARCHAR(4000) NOT NULL,
    local VARCHAR(150) NOT NULL,
    prioridade VARCHAR(20) NOT NULL CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO')),
    data_abertura TIMESTAMP NOT NULL,
    data_fechamento TIMESTAMP,
    solucao VARCHAR(4000),
    solicitante_id BIGINT NOT NULL REFERENCES usuarios(id),
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    tecnico_id BIGINT REFERENCES usuarios(id)
);

CREATE TABLE interacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto VARCHAR(4000) NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    chamado_id BIGINT NOT NULL REFERENCES chamados(id),
    autor_id BIGINT NOT NULL REFERENCES usuarios(id)
);

CREATE INDEX idx_categorias_setor ON categorias(setor_id);
CREATE INDEX idx_usuarios_setor ON usuarios(setor_id);
CREATE INDEX idx_chamados_categoria ON chamados(categoria_id);
CREATE INDEX idx_chamados_solicitante ON chamados(solicitante_id);
CREATE INDEX idx_chamados_tecnico ON chamados(tecnico_id);
CREATE INDEX idx_interacoes_chamado ON interacoes(chamado_id);
